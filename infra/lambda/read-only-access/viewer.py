"""Create the synthetic catalog reader and set its permanent password from Secrets Manager.

The password is generated by Secrets Manager, read once, and sent only to Cognito.
It is never logged, returned, or copied into the custom-resource response.
"""

import json
import re
import secrets
import string

import boto3
from botocore.exceptions import ClientError

USERNAME = "penelope-viewer"
SECRET_NAME = "panther/viewer-credentials"


def _clients():
    return boto3.client("cognito-idp"), boto3.client("secretsmanager")


def _error(error):
    raise RuntimeError(error.response.get("Error", {}).get("Code", "AWS service error")) from None


def _password(secrets_client, secret_id):
    if secret_id != SECRET_NAME:
        raise ValueError("Unexpected credential location")
    try:
        raw = secrets_client.get_secret_value(SecretId=secret_id)["SecretString"]
        value = json.loads(raw).get("password")
    except (ClientError, json.JSONDecodeError, KeyError, TypeError):
        raise RuntimeError("Viewer credential is unreadable") from None
    if not _acceptable(value):
        raise RuntimeError("Viewer credential does not meet the pool policy")
    return value


def _acceptable(value):
    if not isinstance(value, str) or not 16 <= len(value) <= 128 or any(character.isspace() for character in value):
        return False
    return (
        any(character.islower() for character in value)
        and any(character.isupper() for character in value)
        and any(character.isdigit() for character in value)
        and any(not character.isalnum() for character in value)
    )


def _temporary_password():
    groups = [string.ascii_lowercase, string.ascii_uppercase, string.digits, "!@#$%^&*()-_=+"]
    characters = [secrets.choice(group) for group in groups]
    alphabet = "".join(groups)
    characters.extend(secrets.choice(alphabet) for _ in range(20))
    secrets.SystemRandom().shuffle(characters)
    return "".join(characters)


def _ensure_user(cognito, pool, username):
    try:
        cognito.admin_get_user(UserPoolId=pool, Username=username)
        return
    except ClientError as error:
        if error.response.get("Error", {}).get("Code") != "UserNotFoundException":
            _error(error)
    try:
        cognito.admin_create_user(
            UserPoolId=pool,
            Username=username,
            TemporaryPassword=_temporary_password(),
            MessageAction="SUPPRESS",
        )
    except ClientError as error:
        if error.response.get("Error", {}).get("Code") != "UsernameExistsException":
            _error(error)


def ensure_viewer(event, *, cognito, secrets_client):
    if event.get("RequestType") not in {"Create", "Update", "Delete"}:
        raise ValueError("Invalid provisioning operation")
    physical = event.get("PhysicalResourceId") or USERNAME
    if event["RequestType"] == "Delete":
        return {"PhysicalResourceId": physical}
    props = event.get("ResourceProperties") or {}
    username = props.get("Username")
    pool = props.get("UserPoolId")
    if username != USERNAME or not isinstance(pool, str) or not re.fullmatch(r"[\w-]{1,64}", pool):
        raise ValueError("Unexpected account")
    password = _password(secrets_client, props.get("SecretId"))
    _ensure_user(cognito, pool, username)
    try:
        cognito.admin_set_user_password(
            UserPoolId=pool, Username=username, Password=password, Permanent=True,
        )
    except ClientError as error:
        _error(error)
    return {"PhysicalResourceId": f"{pool}:{username}"}


def handler(event, _context):
    cognito, secrets_client = _clients()
    return ensure_viewer(event, cognito=cognito, secrets_client=secrets_client)
