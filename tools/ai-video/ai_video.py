#!/usr/bin/env python3
"""Audio-first AI session video runner (plan 14). See docs/ai-video-process.md.

Generic: everything game-specific lives in the session folder (shotbook.json, cast sheets, audio,
takes, ledger), which is synced with the session artifacts, never committed here.

Commands (run from anywhere; SESSION is the session folder):
  validate SESSION                  check the shot book and report the worst-case cost
  sheet SESSION CAST_ID             painted reference sheet from the pinned portraits
  frame SESSION SHOT_ID             composed first frame from the cast sheets
  take SESSION SHOT_ID [--defect D] one paid take (a re-roll needs a named defect; max 3 takes)
  review SESSION SHOT_ID TAKE (--accept | --reject DEFECT) [--offset S]
  cut SESSION                       chosen takes on the master timeline + the master mix at -14 LUFS
  ledger SESSION                    spend so far against the cap

The OpenRouter key comes from OPENROUTER_API_KEY (or OPENROUTER_KEY_FILE pointing at a file that
holds only the key). It is never printed. Dialogue audio must be an HTTPS URL; put presigned URLs in
SESSION/audio-urls.json ({"L06": "https://..."}), generated by the session's presign step.
"""

import argparse
import base64
import json
import math
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

API = "https://openrouter.ai/api/v1"
DEFAULT_CAP_USD = 9.00
MAX_TAKES = 3
DEFECTS = {
    "lip-sync",
    "identity",
    "hands-anatomy",
    "wrong-action",
    "artefact",
    "continuity",
    "camera",
}
IMAGE_MODEL = "google/gemini-nano-banana-2.1"
IMAGE_EST_USD = 0.05
ROUTES = {"dialogue": "seedance-2.5", "scene": "h3-max"}
MODELS = {
    "seedance-2.5": {
        "id": "bytedance/seedance-2.5",
        "durations": range(4, 31),
        "sizes": {"480p": "854x480", "720p": "1280x720"},
        "default": "480p",
    },
    "h3-max": {
        "id": "minimax/hailuo-3-max",
        "durations": range(5, 16),
        "usd_per_s": {"480p": 0.05, "768p": 0.08},
        "default": "768p",
    },
}
SEEDANCE_USD_PER_TOKEN = 0.0000107
DROP_FRAMES = 2


class Refused(Exception):
    """A guard refused the action; nothing was spent."""


# ---------- shot book ----------


def load(session):
    session = Path(session)
    book = json.loads((session / "shotbook.json").read_text())
    validate(book)
    return session, book


def route(shot):
    model = shot.get("model") or ROUTES[shot["kind"]]
    if model not in MODELS:
        raise Refused(f"{shot['id']}: unknown model {model}")
    if shot["kind"] == "dialogue" and model != "seedance-2.5":
        raise Refused(f"{shot['id']}: dialogue shots use Seedance 2.5 (audio-driven lip sync)")
    return model


def billed_seconds(shot):
    model = route(shot)
    lo = min(MODELS[model]["durations"])
    return max(lo, math.ceil(shot["duration"] - 1e-9))


def resolution(shot):
    return shot.get("resolution") or MODELS[route(shot)]["default"]


def estimate(shot):
    """Conservative USD estimate for one take."""
    model, seconds, res = route(shot), billed_seconds(shot), resolution(shot)
    if model == "seedance-2.5":
        w, h = (int(v) for v in MODELS[model]["sizes"][res].split("x"))
        return round(w * h * 24 * seconds / 1024 * SEEDANCE_USD_PER_TOKEN * 1.02, 4)
    return round(MODELS[model]["usd_per_s"][res] * seconds, 4)


def validate(book):
    cast, lines, shots = book.get("cast", {}), book.get("lines", {}), book.get("shots", [])
    if not shots:
        raise Refused("The shot book has no shots")
    for cid, c in cast.items():
        if not isinstance(c.get("identity"), str) or len(c["identity"].strip()) < 40:
            raise Refused(f"cast {cid}: identity block missing or too short")
    seen, cursor = set(), None
    for shot in shots:
        sid = shot.get("id")
        if not sid or sid in seen:
            raise Refused(f"duplicate or missing shot id {sid!r}")
        seen.add(sid)
        if shot.get("kind") not in ROUTES:
            raise Refused(f"{sid}: kind must be dialogue or scene")
        if not 2 <= shot.get("duration", 0) <= 12:
            raise Refused(f"{sid}: shots are 2-12 seconds")
        if cursor is not None and abs(shot["start"] - cursor) > 0.05:
            raise Refused(
                f"{sid}: starts at {shot['start']} but the previous shot ends at {cursor:.2f}"
            )
        cursor = shot["start"] + shot["duration"]
        model = route(shot)
        if billed_seconds(shot) not in MODELS[model]["durations"]:
            raise Refused(f"{sid}: {model} cannot make {billed_seconds(shot)} s")
        for cid in shot.get("cast", []):
            if cid not in cast:
                raise Refused(f"{sid}: cast {cid} is not locked")
            if cast[cid]["identity"].strip() not in shot.get("prompt", ""):
                raise Refused(f"{sid}: prompt lacks the identity block for {cid}")
        if shot["kind"] == "dialogue":
            if shot.get("line") not in lines:
                raise Refused(f"{sid}: a dialogue shot needs one locked line")
            if lines[shot["line"]].get("speaker") not in shot.get("cast", []):
                raise Refused(f"{sid}: the speaker of {shot['line']} must be visible")
    return True


def worst_case(book):
    takes = sum(estimate(s) for s in book["shots"])
    images = IMAGE_EST_USD * (len(book["shots"]) + len(book.get("cast", {})))
    return {
        "oneTakeUsd": round(takes + images, 2),
        "allRerollsUsd": round(takes * MAX_TAKES + images, 2),
        "capUsd": book.get("budgetUsd", DEFAULT_CAP_USD),
    }


# ---------- budget ledger ----------


class Ledger:
    def __init__(self, session, cap):
        self.path = Path(session) / "ledger.json"
        self.data = (
            json.loads(self.path.read_text())
            if self.path.exists()
            else {"capUsd": cap, "entries": []}
        )
        self.data["capUsd"] = min(self.data.get("capUsd", cap), cap)

    def save(self):
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.data, indent=1))
        tmp.replace(self.path)

    def committed(self):
        return round(
            sum(
                e["costUsd"] if e.get("costUsd") is not None else e["estUsd"]
                for e in self.data["entries"]
            ),
            4,
        )

    def reserve(self, what, est):
        if self.committed() + est > self.data["capUsd"] + 1e-9:
            raise Refused(
                f"Budget guard: {what} needs ${est:.2f}; ${self.committed():.2f} of ${self.data['capUsd']:.2f} is committed"
            )
        entry = {"what": what, "estUsd": est, "costUsd": None, "at": int(time.time())}
        self.data["entries"].append(entry)
        self.save()
        return entry

    def settle(self, entry, cost, **extra):
        entry["costUsd"] = cost
        entry.update(extra)
        self.save()


# ---------- takes ----------


def takes_file(session):
    return Path(session) / "takes.json"


def take_state(session):
    p = takes_file(session)
    return json.loads(p.read_text()) if p.exists() else {}


def check_take(state, shot_id, defect):
    prior = state.get(shot_id, [])
    if len(prior) >= MAX_TAKES:
        raise Refused(f"{shot_id}: already {MAX_TAKES} takes; no more re-rolls")
    if prior and defect not in DEFECTS:
        raise Refused(f"{shot_id}: a re-roll needs a named defect ({', '.join(sorted(DEFECTS))})")
    if prior and not any(t.get("rejected") == defect for t in prior):
        raise Refused(f"{shot_id}: reject a take for {defect} in review before re-rolling for it")
    if any(t.get("accepted") for t in prior):
        raise Refused(f"{shot_id}: a take is already accepted")
    return len(prior) + 1


# ---------- OpenRouter ----------


def api_key():
    key = os.environ.get("OPENROUTER_API_KEY", "").strip()
    if not key and os.environ.get("OPENROUTER_KEY_FILE"):
        key = Path(os.environ["OPENROUTER_KEY_FILE"]).read_text().strip()
    if not key:
        raise Refused("Set OPENROUTER_API_KEY or OPENROUTER_KEY_FILE")
    return key


def call(method, path, body=None, raw=False):
    req = urllib.request.Request(
        API + path,
        method=method,
        data=json.dumps(body).encode() if body else None,
        headers={"Authorization": "Bearer " + api_key(), "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            data = r.read()
    except urllib.error.HTTPError as e:
        raise Refused(f"OpenRouter {e.code}: {e.read()[:400].decode(errors='replace')}") from None
    return data if raw else json.loads(data)


def data_url(path):
    path = Path(path)
    mime = "image/png" if path.suffix == ".png" else "image/jpeg"
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()


def image(prompt, refs, out, aspect):
    content = [{"type": "text", "text": prompt}] + [
        {"type": "image_url", "image_url": {"url": data_url(r)}} for r in refs
    ]
    r = call(
        "POST",
        "/chat/completions",
        {
            "model": IMAGE_MODEL,
            "modalities": ["image", "text"],
            "image_config": {"aspect_ratio": aspect},
            "messages": [{"role": "user", "content": content}],
        },
    )
    msg = r["choices"][0]["message"]
    url = (msg.get("images") or [{}])[0].get("image_url", {}).get("url", "")
    if not url.startswith("data:"):
        raise Refused("The image model returned no image")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_bytes(base64.b64decode(url.split(",", 1)[1]))
    return (r.get("usage") or {}).get("cost")


def video_body(session, book, shot):
    model, res = route(shot), resolution(shot)
    frame = Path(session) / "frames" / f"{shot['id']}.png"
    body = {
        "model": MODELS[model]["id"],
        "duration": billed_seconds(shot),
        "prompt": shot["prompt"],
    }
    if frame.exists():
        body["frame_images"] = [
            {
                "type": "image_url",
                "image_url": {"url": data_url(frame)},
                "frame_type": "first_frame",
            }
        ]
    if model == "seedance-2.5":
        urls = json.loads((Path(session) / "audio-urls.json").read_text())
        refs = [
            {
                "type": "image_url",
                "image_url": {"url": data_url(Path(session) / book["cast"][c]["sheet"])},
            }
            for c in shot.get("cast", [])
        ][:3]
        refs.append({"type": "audio_url", "audio_url": {"url": urls[shot["line"]]}})
        body.update(size=MODELS[model]["sizes"][res], generate_audio=True, input_references=refs)
    else:
        body.update(resolution=res, aspect_ratio="16:9")
    return body


def run_take(session, book, shot_id, defect=None, poll=15):
    shot = next(s for s in book["shots"] if s["id"] == shot_id)
    state = take_state(session)
    n = check_take(state, shot_id, defect)
    ledger = Ledger(session, book.get("budgetUsd", DEFAULT_CAP_USD))
    body = video_body(session, book, shot)
    entry = ledger.reserve(f"take {shot_id}#{n}", estimate(shot))
    try:
        job = call("POST", "/videos", body)
    except Refused:
        ledger.settle(entry, 0.0, status="rejected")
        raise
    while True:
        time.sleep(poll)
        status = call("GET", f"/videos/{job['id']}")
        if status.get("status") in {"completed", "failed", "cancelled", "expired"}:
            break
    cost = (status.get("usage") or {}).get("cost")
    out = Path(session) / "takes" / shot_id / f"take-{n}.mp4"
    record = {"take": n, "job": job["id"], "status": status["status"], "defectFixed": defect}
    if status["status"] == "completed":
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(call("GET", f"/videos/{job['id']}/content?index=0", raw=True))
        record["path"] = str(out.relative_to(session))
    ledger.settle(
        entry,
        cost if cost is not None else (entry["estUsd"] if status["status"] == "completed" else 0.0),
        job=job["id"],
        status=status["status"],
    )
    state.setdefault(shot_id, []).append(record)
    takes_file(session).write_text(json.dumps(state, indent=1))
    return record


def review(session, shot_id, take, accept=False, reject=None, offset=None):
    state = take_state(session)
    t = next(t for t in state.get(shot_id, []) if t["take"] == take)
    if reject:
        if reject not in DEFECTS:
            raise Refused(f"Unknown defect {reject}")
        t["rejected"] = reject
    if accept:
        for other in state[shot_id]:
            other.pop("accepted", None)
        t["accepted"] = True
    if offset is not None:
        t["nudge"] = offset
    takes_file(session).write_text(json.dumps(state, indent=1))
    return t


# ---------- sync and cut ----------


def ff(*args):
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *args], check=True)


def probe_fps(path):
    out = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "v:0",
            "-show_entries",
            "stream=r_frame_rate",
            "-of",
            "csv=p=0",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    a, b = out.split("/")
    return float(a) / float(b)


def decode(path, w, h):
    import numpy as np

    raw = subprocess.run(
        [
            "ffmpeg",
            "-loglevel",
            "error",
            "-i",
            str(path),
            "-an",
            "-vf",
            f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},setsar=1",
            "-f",
            "rawvideo",
            "-pix_fmt",
            "rgb24",
            "-",
        ],
        capture_output=True,
        check=True,
    ).stdout
    return np.frombuffer(raw, np.uint8).reshape(-1, h, w, 3)


def clip_times(shot, line, knots, fps):
    """Clip time for each output frame of the shot; dialogue follows the line map, the rest runs at 1x."""
    from sync import at

    times = []
    for k in range(round(shot["duration"] * fps)):
        master = shot["start"] + k / fps
        if line is None:
            times.append(DROP_FRAMES / fps + (master - shot["start"]))
        else:
            times.append(at(knots, master - line["start"]))
    return times


def sync_take(session, book, shot, take):
    from sync import line_map

    line = book["lines"][shot["line"]]
    knots, cost = line_map(Path(session) / take["path"], Path(session) / line["audio"])
    take["map"], take["syncCost"] = knots, cost
    return knots, cost


def cut(session, book, out=None):
    session = Path(session)
    state = take_state(session)
    work = session / "cut"
    work.mkdir(exist_ok=True)
    fps = book.get("fps", 24)
    w, h = (int(v) for v in book.get("size", "1280x720").split("x"))
    picture = work / "picture.mp4"
    enc = subprocess.Popen(
        [
            "ffmpeg",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "rawvideo",
            "-pix_fmt",
            "rgb24",
            "-s",
            f"{w}x{h}",
            "-r",
            str(fps),
            "-i",
            "-",
            "-c:v",
            "libx264",
            "-preset",
            "medium",
            "-crf",
            "18",
            "-pix_fmt",
            "yuv420p",
            str(picture),
        ],
        stdin=subprocess.PIPE,
    )
    report = []
    for shot in book["shots"]:
        chosen = next((t for t in state.get(shot["id"], []) if t.get("accepted")), None)
        if not chosen:
            enc.kill()
            raise Refused(f"{shot['id']}: no accepted take")
        line = book["lines"][shot["line"]] if shot["kind"] == "dialogue" else None
        knots = None
        if line is not None:
            knots = chosen.get("map") or sync_take(session, book, shot, chosen)[0]
            knots = [[a, b + chosen.get("nudge", 0.0)] for a, b in knots]
        frames = decode(session / chosen["path"], w, h)
        native = probe_fps(session / chosen["path"])
        times = clip_times(shot, line, knots, fps)
        idx = [min(max(int(round(t * native)), DROP_FRAMES), len(frames) - 1) for t in times]
        for i in idx:
            enc.stdin.write(frames[i].tobytes())
        report.append(
            {
                "shot": shot["id"],
                "take": chosen["take"],
                "firstFrame": idx[0],
                "lastFrame": idx[-1],
                "syncCost": chosen.get("syncCost"),
            }
        )
        del frames
    enc.stdin.close()
    if enc.wait():
        raise Refused("Picture encode failed")
    takes_file(session).write_text(json.dumps(state, indent=1))
    out = Path(out or session / "out" / book.get("output", "session.mp4"))
    out.parent.mkdir(parents=True, exist_ok=True)
    vf = book.get("overlayFilter", "null")
    ff(
        "-i",
        str(picture),
        "-i",
        str(session / book["master"]["mix"]),
        "-filter_complex",
        f"[0:v]{vf}[v];[1:a]loudnorm=I=-14:TP=-1.5:LRA=11[a]",
        "-map",
        "[v]",
        "-map",
        "[a]",
        "-c:v",
        "libx264",
        "-preset",
        "medium",
        "-crf",
        "18",
        "-pix_fmt",
        "yuv420p",
        "-c:a",
        "aac",
        "-b:a",
        "192k",
        "-shortest",
        "-movflags",
        "+faststart",
        str(out),
    )
    (work / "cut-report.json").write_text(json.dumps(report, indent=1))
    return out


# ---------- CLI ----------


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("validate", "cut", "ledger"):
        sub.add_parser(name).add_argument("session")
    for name, args in (
        ("sheet", ("cast_id",)),
        ("frame", ("shot_id",)),
        ("take", ("shot_id",)),
        ("review", ("shot_id",)),
    ):
        parser = sub.add_parser(name)
        parser.add_argument("session")
        for arg in args:
            parser.add_argument(arg)
        if name == "take":
            parser.add_argument("--defect")
        if name == "review":
            parser.add_argument("take", type=int)
            parser.add_argument("--accept", action="store_true")
            parser.add_argument("--reject")
            parser.add_argument("--nudge", type=float)
    a = p.parse_args(argv)
    try:
        session, book = load(a.session)
        cap = book.get("budgetUsd", DEFAULT_CAP_USD)
        if cap > DEFAULT_CAP_USD and not book.get("budgetOwnerApproved"):
            raise Refused(f"budgetUsd above ${DEFAULT_CAP_USD:.2f} needs budgetOwnerApproved")
        if a.cmd == "validate":
            print(json.dumps(worst_case(book), indent=1))
        elif a.cmd == "ledger":
            led = Ledger(session, cap)
            print(json.dumps({"committedUsd": led.committed(), "capUsd": led.data["capUsd"]}))
        elif a.cmd == "sheet":
            c = book["cast"][a.cast_id]
            led = Ledger(session, cap)
            e = led.reserve(f"sheet {a.cast_id}", IMAGE_EST_USD)
            prompt = (
                book.get(
                    "sheetPrompt",
                    "Character reference sheet in {style}. Left: face-on head and shoulders. Right: front, three-quarter and back full-length views, neutral grey background, even light, no text.",
                ).format(style=book.get("style", "the painted game-portrait style"))
                + " "
                + c["identity"]
            )
            led.settle(
                e,
                image(
                    prompt,
                    [session / r for r in c.get("portraits", [])],
                    session / c["sheet"],
                    "16:9",
                )
                or IMAGE_EST_USD,
            )
        elif a.cmd == "frame":
            shot = next(s for s in book["shots"] if s["id"] == a.shot_id)
            led = Ledger(session, cap)
            e = led.reserve(f"frame {a.shot_id}", IMAGE_EST_USD)
            refs = [session / book["cast"][c]["sheet"] for c in shot.get("cast", [])]
            prompt = (
                f"Opening frame of a film shot in {book.get('style', 'the painted game-portrait style')}, 16:9. {shot['frame']} "
                + " ".join(book["cast"][c]["identity"] for c in shot.get("cast", []))
                + " No text, no borders, not a contact sheet."
            )
            led.settle(
                e,
                image(prompt, refs, session / "frames" / f"{a.shot_id}.png", "16:9")
                or IMAGE_EST_USD,
            )
        elif a.cmd == "take":
            print(json.dumps(run_take(session, book, a.shot_id, a.defect)))
        elif a.cmd == "review":
            print(json.dumps(review(session, a.shot_id, a.take, a.accept, a.reject, a.nudge)))
        elif a.cmd == "cut":
            print(cut(session, book))
    except Refused as error:
        print(f"refused: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
